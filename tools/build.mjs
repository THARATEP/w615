// สร้างไฟล์ที่ได้จากต้นฉบับ (ใช้ Node.js 18+ ไม่ต้องติดตั้งแพ็กเกจเพิ่ม)
//   node tools/build.mjs
// 1) lib/engine.js            -> apps-script/Engine.gs, apps-script/EngineJs.html
// 2) apps-script/*.html       -> web/index.html (เวอร์ชัน PWA ติดตั้งลงเครื่องได้ ทำงานออฟไลน์)
// 3) รายการไฟล์ใน web/        -> web/sw.js (แคชสำหรับใช้งานออฟไลน์ + เลขเวอร์ชัน)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const P = (...a) => join(ROOT, ...a);
const read = (f) => readFileSync(P(f), 'utf8');
const write = (f, s) => { writeFileSync(P(f), s); console.log('  ✓', f); };
const pkg = JSON.parse(read('package.json'));
const VERSION = pkg.version;

console.log(`build v${VERSION}`);

// 1) engine
const engine = read('lib/engine.js');
write('apps-script/Engine.gs', '/* Shared calculation engine (server) – generated from lib/engine.js, do not edit */\n' + engine);
write('apps-script/EngineJs.html', '<script>\n/* generated from lib/engine.js, do not edit */\n' + engine + '\n</script>\n');

// 2) web/index.html
let html = read('apps-script/Index.html');
html = html.replace(/<\?!= include\('(\w+)'\); \?>/g, (_, n) => read(`apps-script/${n}.html`));
const swap = (from, to) => {
  if (!html.includes(from)) throw new Error('build: not found -> ' + from.slice(0, 80));
  html = html.split(from).join(to);
};
swap('  <base target="_top">\n', '');
swap('  <link rel="preconnect" href="https://fonts.googleapis.com">\n', '');
swap('<link href="https://fonts.googleapis.com/css2?family=Sarabun:wght@300;400;500;600;700&family=Prompt:wght@400;500;600&display=swap" rel="stylesheet">', '<link href="fonts/fonts.css" rel="stylesheet">');
swap('https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css', 'vendor/bootstrap.min.css');
swap('https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/font/bootstrap-icons.min.css', 'vendor/bootstrap-icons.min.css');
swap('https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/js/bootstrap.bundle.min.js', 'vendor/bootstrap.bundle.min.js');
swap('https://cdn.jsdelivr.net/npm/sweetalert2@11', 'vendor/sweetalert2.all.min.js');
swap('<!--PWA_HEAD-->', `<meta name="description" content="คำนวณปรับลดราคาในแบบแสดงรายการ ปริมาณงาน และราคา (BOQ) ตามหนังสือ กวจ. ว 651 พร้อมรายงานแนบท้ายสัญญา">
  <meta name="theme-color" content="#0d3b27">
  <meta name="mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
  <meta name="apple-mobile-web-app-title" content="BOQ ว651">
  <link rel="manifest" href="manifest.webmanifest">
  <link rel="icon" href="icons/favicon.ico" sizes="any">
  <link rel="icon" href="icons/icon.svg" type="image/svg+xml">
  <link rel="apple-touch-icon" href="icons/apple-touch-icon.png">`);
swap('<!--PWA_BODY-->', `<script>
window.APP_VERSION = '${VERSION}';
if ('serviceWorker' in navigator && location.protocol !== 'file:') {
  window.addEventListener('load', function () {
    navigator.serviceWorker.register('sw.js').then(function (reg) {
      function offer(w) {
        if (!w || !navigator.serviceWorker.controller) return;
        Swal.fire({ toast: true, position: 'bottom-end', icon: 'info', title: 'มีเวอร์ชันใหม่ของแอป',
          showConfirmButton: true, confirmButtonText: 'อัปเดตเลย', confirmButtonColor: '#16603f' })
          .then(function (r) { if (r.isConfirmed) w.postMessage('skip'); });
      }
      offer(reg.waiting);
      reg.addEventListener('updatefound', function () {
        var w = reg.installing;
        w.addEventListener('statechange', function () { if (w.state === 'installed') offer(w); });
      });
    });
    var reloaded = false;
    navigator.serviceWorker.addEventListener('controllerchange', function () { if (!reloaded) { reloaded = true; location.reload(); } });
  });
}
</script>`);
write('web/index.html', html);

// 3) service worker
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const assets = walk(P('web'))
  .map((f) => relative(P('web'), f).split('\\').join('/'))
  .filter((f) => f !== 'sw.js' && !f.endsWith('.md') && !f.startsWith('.'))
  .sort();
const h = createHash('sha256');
assets.forEach((f) => h.update(f).update(readFileSync(P('web', f))));
const CACHE = `boq-w651-v${VERSION}-${h.digest('hex').slice(0, 8)}`;
write('web/sw.js', `/* Service worker – generated by tools/build.mjs, do not edit */
const CACHE = '${CACHE}';
const ASSETS = ${JSON.stringify(['./', ...assets], null, 1)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)));
});
self.addEventListener('message', (e) => { if (e.data === 'skip') self.skipWaiting(); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
// cache-first (ทำงานออฟไลน์ได้ทั้งหมด) ; หน้าเว็บหลักใช้ network-first เพื่อรับเวอร์ชันใหม่เมื่อออนไลน์
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./index.html', { ignoreSearch: true })));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`);
console.log(`  cache ${CACHE} (${assets.length + 1} files)`);
